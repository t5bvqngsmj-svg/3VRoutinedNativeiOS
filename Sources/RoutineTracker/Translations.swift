enum Language: String, CaseIterable {
    case dutch = "nl"
    case english = "en"
    case german = "de"
    case french = "fr"
    case spanish = "es"
    
    var displayName: String {
        switch self {
        case .dutch: return "Nederlands"
        case .english: return "English"
        case .german: return "Deutsch"
        case .french: return "Français"
        case .spanish: return "Español"
        }
    }
}

